// The generated engine indexes these by direction code, so build the rows in
// code order rather than declaration order.
const PROJ_TABLE = (() => {
  const dx = [], dy = [], facing = [];
  for (const d of PROJECTILE_DIRS) { dx[d.code] = d.dx; dy[d.code] = d.dy; }
  for (const d of DIRECTIONS) {
    const match = PROJECTILE_DIRS.find((p) => p.dx === d.dx && p.dy === d.dy);
    facing[d.code] = match ? match.code : 0;
  }
  return { dx, dy, facing };
})();

// Direction codes by name, so the generated engine cannot drift from the model.
const DIR_CODE = Object.fromEntries(DIRECTIONS.map((d) => [d.key, d.code]));

const SCRIPT_QUEUE_DEPTH = 8;

function cIdent(name, fallback) {
  const id = String(name || '').replace(/[^A-Za-z0-9_]+/g, '_').replace(/^_+|_+$/g, '');
  return id || fallback;
}

function escapeCString(s) {
  let out = '';
  for (const ch of s) {
    const c = ch.charCodeAt(0);
    if (ch === '"') out += '\\"';
    else if (ch === '\\') out += '\\\\';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\f') out += '\\f';
    else if (c >= 32 && c < 127) out += ch;
    else out += '?';
  }
  return out;
}

function byteRows(bytes, perRow = 16, indent = '  ') {
  const parts = [];
  for (let i = 0; i < bytes.length; i += perRow) {
    parts.push(indent + Array.from(bytes.slice(i, i + perRow), (b) => '0x' + b.toString(16).padStart(2, '0')).join(', ') + ',');
  }
  return parts.join('\n');
}

// Public helper for the Image Tool: raw Arduboy-format C array for an image.
export function bitmapToCArray(name, bytes, w, h, withHeader) {
  const all = withHeader ? [w, h, ...bytes] : [...bytes];
  return `// ${w}x${h}${withHeader ? ' (Sprites format: width, height, data)' : ''}\n` +
    `const uint8_t PROGMEM ${cIdent(name, 'image')}[] = {\n${byteRows(Uint8Array.from(all))}\n};\n`;
}

